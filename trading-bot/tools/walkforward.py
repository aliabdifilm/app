# Parameters worth optimising, with sane search ranges.
#
# Deliberately short. Every extra parameter multiplies the search space and
# the chance of fitting noise; a walk-forward run over six free parameters is
# already generous. Risk settings are NOT optimised - they are a policy
# decision about survival, not a variable to be maximised.
DEFAULT_OPTIMIZE = {
    # name: (start, step, stop)
    "InpMinScore": (0.35, 0.05, 0.60),
    "InpAtrStopTrend": (1.5, 0.5, 3.0),
    "InpRRTrend": (1.5, 0.5, 3.0),
    "InpAdxTrendMin": (20.0, 2.0, 28.0),
    "InpDonchianPeriod": (15, 5, 30),
    "InpTrailAtrMult": (1.5, 0.5, 3.0),
}

# Held fixed across every run so the comparison is apples to apples.
DEFAULT_FIXED = {
    "InpRiskPercent": 0.5,
    "InpMaxPositionsTotal": 4,
    "InpDailyLossLimitPct": 3.0,
    "InpMaxDrawdownPct": 10.0,
    "InpRemoteEnabled": "false",
    "InpLogToFile": "false",
    "InpUseNewsFilter": "false",  # the calendar is unavailable in the tester
    "InpShowPanel": "false",
}


def format_input(name: str, value: Any, optimize: Optional[Tuple] = None) -> str:
    """MT5 [TesterInputs] line: value||start||step||stop||optimize_flag"""
    if optimize is None:
        return f"{name}={value}"
    start, step, stop = optimize
    return f"{name}={start}||{start}||{step}||{stop}||Y"


def write_ini(path: str, *, expert: str, symbol: str, period: str, model: int,
              optimization: int, criterion: int, from_date: date, to_date: date,
              deposit: int, currency: str, leverage: int, report: str,
              optimize_params: Dict[str, Tuple], fixed_params: Dict[str, Any],
              best_params: Optional[Dict[str, Any]] = None) -> None:
    lines: List[str] = []

    for name, value in fixed_params.items():
        lines.append(format_input(name, value))

    if best_params is not None:
        # Out-of-sample run: pin the winners, optimise nothing.
        for name, value in best_params.items():
            lines.append(format_input(name, value))
    else:
        for name, bounds in optimize_params.items():
            lines.append(format_input(name, bounds[0], bounds))

    content = INI_TEMPLATE.format(
        expert=expert, symbol=symbol, period=period, model=model,
        optimization=optimization, criterion=criterion,
        from_date=from_date.strftime("%Y.%m.%d"),
        to_date=to_date.strftime("%Y.%m.%d"),
        deposit=deposit, currency=currency, leverage=leverage,
        report=report, inputs="\n".join(lines),
    )
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(content)


# ----------------------------------------------------------------------
# Report parsing
# ----------------------------------------------------------------------
# MT5 writes its single-run report as HTML with a two-column table. The labels
# are stable across builds; the numbers are locale-formatted, so they are
# normalised before parsing.
REPORT_FIELDS = {
    "net_profit": ["Total Net Profit", "Total net profit"],
    "gross_profit": ["Gross Profit", "Gross profit"],
    "gross_loss": ["Gross Loss", "Gross loss"],
    "profit_factor": ["Profit Factor", "Profit factor"],
    "expected_payoff": ["Expected Payoff", "Expected payoff"],
    "max_drawdown_pct": ["Equity Drawdown Maximal", "Balance Drawdown Maximal"],
    "trades": ["Total Trades", "Total trades"],
    "sharpe": ["Sharpe Ratio", "Sharpe ratio"],
    "recovery_factor": ["Recovery Factor", "Recovery factor"],
}


def _to_number(raw: str) -> Optional[float]:
    if raw is None:
        return None
    text = raw.strip()
    # "1 234.56 (12.34%)" -> take the leading number
    text = re.sub(r"\(.*?\)", "", text)
    text = text.replace("\xa0", "").replace(" ", "").replace("%", "")
    # thousands separators: 1,234.56 or 1.234,56
    if re.match(r"^-?\d{1,3}(,\d{3})+(\.\d+)?$", text):
        text = text.replace(",", "")
    elif re.match(r"^-?\d{1,3}(\.\d{3})+(,\d+)?$", text):
        text = text.replace(".", "").replace(",", ".")
    else:
        text = text.replace(",", ".")
    match = re.search(r"-?\d+(?:\.\d+)?", text)
    return float(match.group()) if match else None


def parse_html_report(path: str) -> Dict[str, Any]:
    """Pull the headline metrics out of an MT5 single-run HTML report."""
    with open(path, "r", encoding="utf-8", errors="ignore") as fh:
        html = fh.read()

    # Flatten the table into a list of cell texts, then read label/value pairs.
    cells = re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", html, re.S | re.I)
    cells = [re.sub(r"<[^>]+>", "", c).replace("&nbsp;", " ").strip() for c in cells]

    out: Dict[str, Any] = {"source": os.path.basename(path)}
    for key, labels in REPORT_FIELDS.items():
        value = None
        for i, cell in enumerate(cells):
            stripped = cell.rstrip(":").strip()
            if any(stripped.lower() == label.lower() for label in labels):
                for j in range(i + 1, min(i + 4, len(cells))):
                    value = _to_number(cells[j])
                    if value is not None:
                        break
                break
        out[key] = value

    # "Equity Drawdown Maximal" reports money then a percentage in brackets.
    for label in ("Equity Drawdown Maximal", "Balance Drawdown Maximal"):
        for i, cell in enumerate(cells):
            if cell.rstrip(":").strip().lower() == label.lower():
                for j in range(i + 1, min(i + 4, len(cells))):
                    pct = re.search(r"\(([\d.,\s]+)%\)", cells[j])
                    if pct:
                        out["max_drawdown_pct"] = _to_number(pct.group(1))
                        break
                break

    return out


# ----------------------------------------------------------------------
# Scoring
# ----------------------------------------------------------------------
def annualised_return(net_profit: float, deposit: float, days: int) -> Optional[float]:
    if deposit <= 0 or days <= 0:
        return None
    total_return = net_profit / deposit
    # simple scaling, not compounding: compounding a 2-month sample into an
    # annual figure produces numbers nobody should act on
    return total_return * (365.0 / days)


def score_walkforward(rows: List[Dict[str, Any]], deposit: float) -> Dict[str, Any]:
    """Aggregate per-window results into a verdict."""
    usable = [r for r in rows if r.get("oos_net_profit") is not None]
    if not usable:
        return {"windows": 0, "verdict": "no out-of-sample results to score"}

    efficiencies = []
    for row in usable:
        is_days = int(row.get("is_days") or 0)
        oos_days = int(row.get("oos_days") or 0)
        is_annual = annualised_return(float(row.get("is_net_profit") or 0.0), deposit, is_days)
        oos_annual = annualised_return(float(row["oos_net_profit"]), deposit, oos_days)
        row["is_annualised"] = is_annual
        row["oos_annualised"] = oos_annual
        # Efficiency is only meaningful when the in-sample run actually made
        # money. A negative in-sample result means the optimisation failed,
        # not that the strategy is robust.
        if is_annual and is_annual > 0 and oos_annual is not None:
            row["efficiency"] = oos_annual / is_annual
            efficiencies.append(row["efficiency"])
        else:
            row["efficiency"] = None

    oos_profits = [float(r["oos_net_profit"]) for r in usable]
    profitable = [p for p in oos_profits if p > 0]
    total_oos = sum(oos_profits)

    drawdowns = [float(r["oos_max_drawdown_pct"]) for r in usable
                 if r.get("oos_max_drawdown_pct") is not None]
    trades = sum(int(r.get("oos_trades") or 0) for r in usable)

    mean_efficiency = sum(efficiencies) / len(efficiencies) if efficiencies else None
    consistency = 100.0 * len(profitable) / len(usable)

    # The verdict is intentionally conservative. These thresholds come from
    # standard walk-forward practice, not from this strategy's own results.
    if total_oos <= 0:
        verdict = "REJECT - out-of-sample is net negative"
    elif trades < 100:
        verdict = "INCONCLUSIVE - fewer than 100 out-of-sample trades"
    elif mean_efficiency is not None and mean_efficiency < 0.35:
        verdict = "REJECT - out-of-sample keeps under 35% of in-sample performance"
    elif consistency < 50.0:
        verdict = "REJECT - fewer than half the out-of-sample windows were profitable"
    elif mean_efficiency is not None and mean_efficiency > 1.5:
        verdict = "SUSPICIOUS - out-of-sample beats in-sample; check for look-ahead bias"
    elif mean_efficiency is not None and mean_efficiency >= 0.5 and consistency >= 60.0:
        verdict = "PASS - candidate for demo forward testing"
    else:
        verdict = "MARGINAL - retest with different windows before risking capital"

    return {
        "windows": len(usable),
        "oos_net_profit": round(total_oos, 2),
        "oos_trades": trades,
        "profitable_windows": len(profitable),
        "consistency_pct": round(consistency, 1),
        "mean_efficiency": round(mean_efficiency, 3) if mean_efficiency is not None else None,
        "worst_oos_window": round(min(oos_profits), 2),
        "best_oos_window": round(max(oos_profits), 2),
        "worst_oos_drawdown_pct": round(max(drawdowns), 2) if drawdowns else None,
        "verdict": verdict,
    }


