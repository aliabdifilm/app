# ----------------------------------------------------------------------
# Window schedule
# ----------------------------------------------------------------------
@dataclass
class Window:
    index: int
    is_start: date
    is_end: date
    oos_start: date
    oos_end: date

    def as_dict(self) -> Dict[str, str]:
        return {
            "index": self.index,
            "is_start": self.is_start.isoformat(),
            "is_end": self.is_end.isoformat(),
            "oos_start": self.oos_start.isoformat(),
            "oos_end": self.oos_end.isoformat(),
        }


def add_months(d: date, months: int) -> date:
    """Calendar-correct month arithmetic, clamping day-of-month overflow."""
    month_index = d.month - 1 + months
    year = d.year + month_index // 12
    month = month_index % 12 + 1
    # 31 January + 1 month must land on 28/29 February, not overflow into March
    for day in range(d.day, 0, -1):
        try:
            return date(year, month, day)
        except ValueError:
            continue
    raise ValueError("unreachable")


def build_windows(start: date, end: date, is_months: int, oos_months: int,
                  anchored: bool = False) -> List[Window]:
    """Rolling (default) or anchored walk-forward windows.

    Rolling  : the in-sample window slides, so old regimes drop out.
    Anchored : the in-sample window only grows from a fixed origin.

    Rolling is the stricter test and the default. Anchored tends to flatter
    a strategy because early, favourable history never leaves the sample.
    """
    if is_months < 1 or oos_months < 1:
        raise ValueError("in-sample and out-of-sample lengths must be at least 1 month")
    if end <= start:
        raise ValueError("end date must be after start date")

    windows: List[Window] = []
    cursor = start
    index = 1

    while True:
        is_start = start if anchored else cursor
        is_end = add_months(cursor, is_months)
        oos_start = is_end
        oos_end = add_months(oos_start, oos_months)

        if oos_end > end:
            break

        windows.append(Window(index, is_start, is_end, oos_start, oos_end))
        cursor = add_months(cursor, oos_months)
        index += 1

        if index > 500:  # guard against a pathological schedule
            break

    if not windows:
        raise ValueError(
            f"the range {start} to {end} is too short for "
            f"{is_months}-month in-sample + {oos_months}-month out-of-sample windows"
        )
    return windows


