@dataclass
class HallData:
    name: str
    city: str
    address: Optional[str]
    phone: Optional[str]
    notes: Optional[str]
    map_url: Optional[str]
    logistics: dict[str, str] = field(default_factory=dict)
    ceremony_types: list[str] = field(default_factory=list)
    default_rent: Optional[int] = None
    single_atelier_per_day: bool = False
    is_active: bool = True


def _map_url(form: Form) -> Optional[str]:
    text = form.text("map_url", "نشانی نقشه", max_len=500)
    if not text:
        return None
    parts = urlsplit(text)
    if parts.scheme not in ("http", "https") or not parts.netloc or " " in text:
        form.error("map_url", "نشانی نقشه باید با https:// شروع شود؛ مثلاً پیوند اشتراک‌گذاریِ نشان یا گوگل‌مپ.")
        return None
    return text


def parse_hall(form: Form, *, editing: bool = False) -> Optional[HallData]:
    name = form.text("name", "نام تالار", required=True, max_len=150)
    city = form.text("city", "شهر", required=True, max_len=80)
    address = form.text("address", "نشانی", max_len=300)
    phone = form.text("phone", "تلفن", max_len=30, digits=True)
    notes = form.text("notes", "توضیحات", max_len=2000, multiline=True)
    map_url = _map_url(form)
    logistics: dict[str, str] = {}
    for key, label in LOGISTICS_LABELS.items():
        value = form.text(f"logistics_{key}", label, max_len=300, digits=(key == "contact_phone"))
        if value:
            logistics[key] = value
    types: list[str] = []
    for raw in form.getlist("ceremony_types"):
        if CeremonyType.is_valid(raw):
            value = CeremonyType.coerce(raw).value
            if value not in types:
                types.append(value)
        else:
            form.error("ceremony_types", "نوع مراسم نامعتبر است.")
    form.values["ceremony_types"] = types
    default_rent = form.money("default_rent", "اجارهٔ پیش‌فرض")
    single = form.boolean("single_atelier_per_day")
    active = form.boolean("is_active") if editing else True
    if not form.ok or name is None or city is None:
        return None
    return HallData(name, city, address, phone, notes, map_url, logistics, types, default_rent, single, active)


def hall_values(hall: Any) -> dict[str, Any]:
    """The form values that describe an existing hall (to pre-fill the edit form)."""
    values: dict[str, Any] = {
        "name": hall.name,
        "city": hall.city,
        "address": hall.address or "",
        "phone": hall.phone or "",
        "notes": hall.notes or "",
        "map_url": hall.map_url or "",
        "default_rent": hall.default_rent if hall.default_rent is not None else "",
        "single_atelier_per_day": hall.single_atelier_per_day,
        "is_active": hall.is_active,
        "ceremony_types": list(hall.default_ceremony_types or []),
    }
    for key in LOGISTICS_LABELS:
        values[f"logistics_{key}"] = (hall.logistics or {}).get(key, "")
    return values


