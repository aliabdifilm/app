def parse_event(form: Form) -> Optional[EventData]:
    """The fields of one ceremony: date, start time, kind, guests, title, notes."""
    day = form.date("date", "تاریخ مراسم", required=True)
    start_time = form.time("start_time", "ساعت شروع")
    ceremony_type = form.enum("ceremony_type", "نوع مراسم", CeremonyType, default=CeremonyType.WEDDING)
    guests = form.integer("guests", "تعداد میهمان", min=0, max=MAX_GUESTS)
    title = form.text("title", "عنوان مراسم", max_len=150)
    notes = form.text("notes", "توضیحات", max_len=2000, multiline=True)
    if not form.ok or day is None:
        return None
    return EventData(day, start_time, ceremony_type or CeremonyType.WEDDING, guests, title, notes)


@dataclass
class BulkInput:
    """A "many dates" form: the dates, up to two start times and the shared ceremony fields."""

    days: list[dt.date]
    times: list[Optional[dt.time]]
    data: EventData  # ``day`` is a placeholder (the first date)


def _bad_dates_message(bad: list[dates.BadDate]) -> str:
    shown = "؛ ".join(f"«{to_persian_digits(item.token)}»: {item.message}" for item in bad[:4])
    extra = len(bad) - 4
    return shown + (f"؛ و {to_persian_digits(extra)} مورد دیگر." if extra > 0 else "")


def _rule_dates(form: Form) -> list[dt.date]:
    """Dates produced by the repeat rule fields (weekly / monthly); records errors on the form."""
    mode = form.choice("rule_mode", "الگوی تکرار", ("", "weekly", "monthly"), default="")
    if not mode:
        return []
    if not form.raw("rule_from") and not form.raw("rule_to"):
        return []  # a pre-selected pattern with empty dates is simply not used
    start = form.date("rule_from", "از تاریخ", required=True)
    end = form.date("rule_to", "تا تاریخ", required=True)
    if start is None or end is None:
        return []
    try:
        if mode == "weekly":
            weekdays: list[int] = []
            for raw in form.getlist("rule_weekdays"):
                digits = normalize_digits(raw)
                if digits.isdigit() and 0 <= int(digits) <= 6:
                    weekdays.append(int(digits))
            if not weekdays:
                form.error("rule_weekdays", "دست‌کم یک روز هفته را انتخاب کنید.")
                return []
            return dates.weekly(start, end, weekdays)
        days: list[int] = []
        for part in normalize_digits(form.raw("rule_days")).replace("،", ",").replace(" ", ",").split(","):
            if part.isdigit() and 1 <= int(part) <= 31:
                days.append(int(part))
            elif part:
                form.error("rule_days", "روزهای ماه را با ویرگول بنویسید؛ هر روز عددی از ۱ تا ۳۱.")
                return []
        if not days:
            form.error("rule_days", "دست‌کم یک روز ماه را بنویسید؛ مثلاً ۱ و ۱۵.")
            return []
        short = form.choice("rule_short", "ماه‌های کوتاه", ("clamp", "skip"), default="clamp")
        return dates.monthly(start, end, days, short_month=short or "clamp")
    except ValueError as exc:
        form.error("rule_to", str(exc))
        return []


def parse_bulk(form: Form) -> Optional[BulkInput]:
    """Dates picked on the calendar (``dates``), typed (``dates_text``) or generated by a rule; times; shared fields."""
    picked: list[dt.date] = []
    bad: list[dates.BadDate] = []
    for raw in form.getlist("dates"):
        try:
            picked.append(dates.parse_token(raw))
        except ValueError as exc:
            bad.append(dates.BadDate(raw, str(exc)))
    typed_text = form.text("dates_text", "تاریخ‌ها", multiline=True, max_len=20000)
    typed, typed_bad = dates.parse_many(typed_text or "")
    bad.extend(typed_bad)
    if bad:
        form.error("dates_text", _bad_dates_message(bad))
    generated = _rule_dates(form)
    days = dates.merge(picked, typed, generated)
    form.values["dates"] = [day.isoformat() for day in days]
    form.values["rule_weekdays"] = form.getlist("rule_weekdays")
    if not days and form.ok:
        form.error("dates", "دست‌کم یک تاریخ را انتخاب یا وارد کنید.")
    if len(days) > dates.MAX_BULK_DATES:
        form.error("dates", f"در هر بار حداکثر {to_persian_digits(dates.MAX_BULK_DATES)} تاریخ مجاز است.")

    times: list[Optional[dt.time]] = []
    first = form.time("start_time", "ساعت شروع")
    second = form.time("start_time_2", "ساعت دوم")
    for value in (first, second):
        if value is not None and value not in times:
            times.append(value)
    if not times:
        times.append(None)

    ceremony_type = form.enum("ceremony_type", "نوع مراسم", CeremonyType, default=CeremonyType.WEDDING)
    guests = form.integer("guests", "تعداد میهمان", min=0, max=MAX_GUESTS)
    title = form.text("title", "عنوان مراسم", max_len=150)
    notes = form.text("notes", "توضیحات", max_len=2000, multiline=True)
    if not form.ok:
        return None
    data = EventData(days[0], times[0], ceremony_type or CeremonyType.WEDDING, guests, title, notes)
    return BulkInput(days, times, data)


