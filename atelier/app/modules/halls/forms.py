"""Parsing of the hall panel's HTML forms (digits, Toman, Jalali dates) into plain Python values.

Each ``parse_*`` function reads a :class:`app.services.forms.Form`, records Persian messages on
it and returns a data object (or ``None`` when something is wrong).  The caller checks
``form.ok`` and re-renders with ``form.context()`` and status 422.
"""

