def parse_review(form: Form) -> Optional[tuple[int, Optional[str]]]:
    rating = form.integer("rating", "امتیاز", required=True, min=1, max=5)
    comment = form.text("comment", "نظر", max_len=1000, multiline=True)
    if not form.ok or rating is None:
        return None
    return rating, comment


def parse_agreement(form: Form, atelier: Any) -> Optional[AgreementData]:
    start = form.date("start_date", "تاریخ شروع", required=True)
    end = form.date("end_date", "تاریخ پایان")
    exclusive = form.boolean("is_exclusive")
    rent = form.money("rent_per_event", "اجارهٔ هر مراسم")
    share = form.integer("revenue_share_percent", "درصد سهم تالار", min=0, max=100)
    deposit = form.money("deposit", "مبلغ بیعانه")
    contact_name = form.text("contact_name", "نام مسئول", max_len=120)
    contact_phone = form.text("contact_phone", "تلفن مسئول", max_len=30, digits=True)
    notes = form.text("notes", "توضیحات", max_len=2000, multiline=True)
    if form.ok and start is not None and end is not None and end < start:
        form.error("end_date", "تاریخ پایان نباید پیش از تاریخ شروع باشد.")
    if form.ok and rent is not None and share is not None:
        form.error("revenue_share_percent", "یا اجارهٔ هر مراسم را بنویسید یا درصد سهم؛ هر دو با هم معنی ندارد.")
    if not form.ok or start is None:
        return None
    return AgreementData(atelier, start, end, exclusive, rent, share, deposit, contact_name, contact_phone, notes)


def agreement_values(agreement: Any) -> dict[str, Any]:
    return {
        "start_date": agreement.start_date.isoformat(),
        "end_date": agreement.end_date.isoformat() if agreement.end_date else "",
        "is_exclusive": agreement.is_exclusive,
        "rent_per_event": agreement.rent_per_event if agreement.rent_per_event is not None else "",
        "revenue_share_percent": agreement.revenue_share_percent if agreement.revenue_share_percent is not None else "",
        "deposit": agreement.deposit if agreement.deposit is not None else "",
        "contact_name": agreement.contact_name or "",
        "contact_phone": agreement.contact_phone or "",
        "notes": agreement.notes or "",
    }


def event_values(event: Any) -> dict[str, Any]:
    return {
        "date": event.date.isoformat(),
        "start_time": event.start_time.strftime("%H:%M") if event.start_time else "",
        "ceremony_type": event.ceremony_type.value,
        "guests": event.guest_count_estimate if event.guest_count_estimate is not None else "",
        "title": event.title or "",
        "notes": event.notes or "",
    }
