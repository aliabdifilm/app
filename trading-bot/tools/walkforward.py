"""Walk-forward analysis driver for the ApexAlgo EA.

THE PROBLEM THIS SOLVES
    Run the MT5 optimiser over three years of EURUSD and it will hand you a
    parameter set with a beautiful equity curve. Trade it and it falls apart.
    The optimiser did not find an edge; it found the settings that best
    describe the noise in that particular slice of history.

THE FIX
    Split history into consecutive windows. Optimise on the first part of a
    window (in-sample), then test the winning parameters on the part that
    immediately follows and was never optimised on (out-of-sample). Slide
    forward and repeat. The out-of-sample results, stitched together, are the
    closest honest estimate of live behaviour you can get from history.

    The headline number is Walk-Forward Efficiency:

        WFE = out-of-sample return / in-sample return   (annualised)

    A robust system keeps a decent chunk of its in-sample performance. A
    curve-fitted one keeps almost none.

USAGE
    # 1. See the schedule and write the tester config files (any platform)
    python walkforward.py plan --start 2023-01-01 --end 2026-06-30 \
        --is-months 6 --oos-months 2 --symbol EURUSD

    # 2. Run them through the terminal (Windows, terminal must be closed)
    python walkforward.py run --terminal "C:\\Program Files\\MetaTrader 5\\terminal64.exe"

    # 3. Score the results
    python walkforward.py report

Only step 2 needs Windows and a MetaTrader installation. Steps 1 and 3 are
plain Python and are covered by the self-test (`python walkforward.py selftest`).
"""

